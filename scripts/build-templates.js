/**
 * Generates glyph-data.js from the JSON stores.
 *
 * It exists for one reason: the webapp is opened by double-click, over file://,
 * and browsers block fetch() of .json under that scheme. The .json files remain
 * the source of truth (versioned, diffable, read by Node and by the test
 * suite); this script produces the copy a <script src> can actually load.
 *
 *   node build-templates.js
 */

"use strict";

const fs = require("fs");
const path = require("path");
const X = require("./read-expansoes.js");

/* Two roots since the granulation: scripts hold JavaScript, the repository
   root holds the data a human edits (.json, .txt) and the app itself. The
   generated glyph-data.js is JavaScript, so it lands here; the generated
   glyph-expansions.json is data, so it lands at the root, next to the other
   stores. The rule is the file's kind, not who wrote it. */
const HERE = __dirname;
const ROOT = path.join(__dirname, "..");

/* The definitions live in GLOSSARIO.md, in prose, and until v1.2.1.0 the engine
   could not reach them. That left the message unable to explain itself where it
   matters most: `made-of` describes a composite for free, but the 88
   hieroglyphs — precisely what does NOT decompose — had nothing to say beyond
   an English label. `means="Review"` adds nothing to `<review>`.

   Extracted rather than copied into a second file, because the glossary is the
   normative reference and the engine derives from it. Copying would create the
   same drift this whole version was spent closing.

   Entry shape:   `NAME` [★|⚠] [= `formula`] — Label. Definition…
   Six engine entries carry no English label, and there the whole line is the
   definition. */
const GLOSS_LINE = /^`([A-Z][A-Z0-9_]*)`\s*(?:[★⚠]\s*)*(?:=\s*`[^`]*`\s*)?—\s*(.+?)\s*$/;

function stripMd(s) {
  return String(s)
    .replace(/\*\(.*?\)\*\s*$/, "")     // nota em itálico no fim
    .replace(/\*\*/g, "").replace(/`/g, "")
    .replace(/\s+/g, " ").trim();
}

function readGlossary() {
  const src = path.join(ROOT, "GLOSSARIO.md");
  if (!fs.existsSync(src)) { console.error("  ! GLOSSARIO.md not found."); return {}; }
  const defs = {};
  fs.readFileSync(src, "utf8").split(/\r?\n/).forEach(ln => {
    const m = GLOSS_LINE.exec(ln.trim());
    if (!m) return;
    const body = stripMd(m[2]);
    /* O rótulo em inglês é curto ("Do not.", "See also."). Um primeiro
       segmento longo não é rótulo — é a definição inteira. */
    const dot = body.indexOf(". ");
    const head = dot > 0 ? body.slice(0, dot) : "";
    const isLabel = head && head.split(/\s+/).length <= 3;
    defs[m[1]] = isLabel ? body.slice(dot + 2).trim() : body.replace(/\.$/, "").trim() + ".";
  });
  return defs;
}

/* expansoes.txt is not JSON, so unlike the other two stores it cannot just be
   copied — it is compiled into glyph-expansions.json first, and THAT is what
   both Node and the browser load. The .txt stays the source a human edits:
   one entry per line beats hand-maintaining nested JSON. */
function buildExpansions() {
  const src = path.join(ROOT, "expansoes.txt");
  if (!fs.existsSync(src)) { console.error("  ! expansoes.txt not found."); return null; }

  const { parsed, analysis, commands } = X.build(fs.readFileSync(src, "utf8"));

  /* A table that does not close must not reach the engine: an undefined
     dependency or a cycle means decomposition would silently stop halfway,
     and half-burnt output is worse than none. */
  if (analysis.undefinedDeps.length || analysis.cycles.length) {
    console.error("  ! expansoes.txt does not close — " +
      analysis.undefinedDeps.length + " undefined, " + analysis.cycles.length + " cycles.");
    console.error("    run: node dag.js expansoes.txt");
    process.exit(1);
  }

  /* A definição entra ao lado da composição porque respondem à mesma pergunta
     em dois níveis: `def` diz o que o comando É, `formula` diz do que ele é
     FEITO. Um átomo só tem a primeira — e é exatamente por isso que ela
     precisava existir. */
  const defs = readGlossary();
  const semDef = Object.keys(commands).filter(c => !defs[c]).sort();
  Object.keys(commands).forEach(c => { if (defs[c]) commands[c].def = defs[c]; });

  /* Mesmo portão do ciclo: um comando sem definição volta a ser opaco na
     mensagem, e opaco em silêncio é como a divergência entra. */
  if (semDef.length) {
    console.error("  ! " + semDef.length + " comando(s) sem verbete em GLOSSARIO.md: " + semDef.join(" "));
    console.error("    todo comando de expansoes.txt precisa de uma linha `NOME` — Definição.");
    process.exit(1);
  }
  console.log("  ✓ GLOSSARIO.md -> " + Object.keys(defs).length + " definições");

  const store = {
    schema: 2,
    note: "GENERATED by build-templates.js from expansoes.txt (composition) and " +
          "GLOSSARIO.md (definitions) — DO NOT EDIT BY HAND. Every command carries " +
          "`species` (`atom` = a hieroglyph, does not decompose; `composite` = a glyph, " +
          "with the `formula` that decomposes it), `depth` (0 for an atom, 1 + the " +
          "deepest dependency otherwise) and `def`, what the command means. `def` is " +
          "the only thing an atom has to say about itself.",
    atoms: parsed.atoms.length,
    composites: Object.keys(parsed.composites).length,
    maxDepth: Math.max.apply(null, Object.keys(analysis.depth).map(k => analysis.depth[k])),
    commands: commands
  };

  const out = path.join(ROOT, "glyph-expansions.json");
  fs.writeFileSync(out, JSON.stringify(store, null, 2) + "\n");
  console.log("  ✓ expansoes.txt -> glyph-expansions.json (" +
    store.atoms + " átomos, " + store.composites + " compostos, fundo " + store.maxDepth + ")");
  return store;
}

buildExpansions();

const SOURCES = [
  { file: "glyph-templates.json",   global: "GlyphTemplates" },
  { file: "glyph-rules.json",       global: "GlyphRules" },
  { file: "glyph-expansions.json",  global: "GlyphExpansions" }
];

const parts = [
  "/* GENERATED BY build-templates.js — DO NOT EDIT BY HAND.",
  "   Edit the .json sources and run: node build-templates.js */",
  "(function (root) {",
  '  "use strict";'
];

let missing = 0;
SOURCES.forEach(({ file, global }) => {
  const full = path.join(ROOT, file);
  if (!fs.existsSync(full)) {
    console.error("  ! " + file + " not found — " + global + " will be null.");
    parts.push("  root." + global + " = null;");
    missing++;
    return;
  }
  const raw = fs.readFileSync(full, "utf8");
  JSON.parse(raw); // fail fast on malformed JSON
  /* Normaliza CRLF: no Windows os .json costumam estar com fim de linha do
     sistema, e embutir o conteúdo cru fazia o arquivo GERADO sair misturado —
     LF no que este script escreve, CRLF no que ele copia. Sem efeito nenhum
     em JS, mas o arquivo aparecia como modificado depois de todo build, e
     git status que mente sobre arquivo gerado é git status em que ninguém
     mais olha. */
  parts.push("  root." + global + " = " + raw.replace(/\r\n/g, "\n").trim() + ";");
  console.log("  ✓ " + file + " -> " + global);
});

parts.push("})(typeof self !== \"undefined\" ? self : this);");

const out = path.join(HERE, "glyph-data.js");
fs.writeFileSync(out, parts.join("\n") + "\n");
console.log("generated: glyph-data.js (" + fs.statSync(out).size + " bytes)" +
            (missing ? "  [" + missing + " source(s) missing]" : ""));
